    public static boolean pixel(char c, int x, int y) {
        String[] glyph = GLYPHS.getOrDefault(Character.toUpperCase(c), GLYPHS.get(' '));
        return glyph[y].charAt(x) == '#';
    }

    public static float textWidth(String text, float scale) {
        if (text.isEmpty()) {
            return 0.0f;
        }
        return text.length() * (WIDTH + 1) * scale - scale;
    }

    public static float textHeight(float scale) {
        return HEIGHT * scale;
    }

    private static void glyph(char c, String... rows) {
        GLYPHS.put(c, rows);
    }
